//! Agent skills for the repository that uses devstack (`devstack skills install`).
//!
//! The binary carries the templates (`skills/` in the devstack repository) and
//! fills in what the stack file says: its services, commands, held paths and
//! the URLs to check after a start, into the folders `[agents] skills` names
//! (`.claude/skills` when it names none). A generated skill says so in a
//! marker line; installing again overwrites it, and `devstack status` (and
//! the dashboard, through the hub) notes when an installed copy, in those
//! folders or another agent's, no longer matches this devstack's templates or
//! this stack file (a new version alone does not count). What is
//! specific to a project beyond that belongs in a skill of the project's own,
//! which devstack never touches.

use anyhow::{Context, Result};
use devstack_config::Stack;
use devstack_config::model::{Kind, Service};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const VERSION: &str = devstack_config::VERSION;
const REPO_URL: &str = "https://github.com/nuetzliches/devstack";
/// The words that tell a generated skill from one a project wrote itself.
const MARKER_TAG: &str = "(devstack skills install)";

const TEMPLATES: &[(&str, &str)] = &[
    (
        "devstack",
        include_str!("../../../skills/devstack/SKILL.md"),
    ),
    (
        "devstack-config",
        include_str!("../../../skills/devstack-config/SKILL.md"),
    ),
];

/// The project skill folders coding agents read, relative to the repository:
/// where a generated skill is looked for besides `[agents] skills` (one
/// installed there earlier, or with `--dir`).
pub const KNOWN_DIRS: &[&str] = &[
    ".claude/skills",
    ".agents/skills",
    ".github/skills",
    ".cursor/skills",
    ".gemini/skills",
    ".opencode/skills",
    ".windsurf/skills",
    ".devin/skills",
    ".codex/skills",
];

/// The folders `[agents] skills` names (`.claude/skills` when it names
/// none), in the repository.
pub fn skill_dirs(stack: &Stack, stack_file: &Path) -> Result<Vec<PathBuf>> {
    let repo = repo(stack_file)?;
    Ok(stack
        .agents
        .skill_dirs()
        .iter()
        .map(|d| repo.join(d))
        .collect())
}

/// The folders a generated skill is looked for in: `[agents] skills`, then
/// the other agents' ones, each once.
fn search_dirs(stack: &Stack, stack_file: &Path) -> Result<Vec<PathBuf>> {
    let repo = repo(stack_file)?;
    let mut dirs: Vec<String> = stack.agents.skill_dirs();
    for k in KNOWN_DIRS {
        if !dirs.iter().any(|d| same_dir(d, k)) {
            dirs.push((*k).to_string());
        }
    }
    Ok(dirs.iter().map(|d| repo.join(d)).collect())
}

fn same_dir(a: &str, b: &str) -> bool {
    let n = |s: &str| s.replace('\\', "/").trim_end_matches('/').to_lowercase();
    n(a) == n(b)
}

/// A skill in `dir` (a folder in the repository) by its repository-relative
/// name: `.agents/skills/devstack`.
fn shown(stack_file: &Path, dir: &Path, name: &str) -> String {
    let rel = repo(stack_file)
        .ok()
        .and_then(|r| dir.strip_prefix(r).ok().map(Path::to_path_buf))
        .unwrap_or_else(|| dir.to_path_buf());
    format!("{}/{name}", rel.to_string_lossy().replace('\\', "/"))
}

fn repo(stack_file: &Path) -> Result<PathBuf> {
    let abs = std::path::absolute(stack_file)?;
    Ok(abs.parent().map(Path::to_path_buf).unwrap_or(abs))
}

fn file_name(stack_file: &Path) -> String {
    stack_file
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_else(|| "devstack.toml".into())
}

/// Every skill, rendered for this stack: `(name, content)`.
pub fn render_all(stack: &Stack, stack_file: &Path) -> Vec<(&'static str, String)> {
    TEMPLATES
        .iter()
        .map(|(name, tpl)| (*name, render(tpl, stack, stack_file, VERSION)))
        .collect()
}

/// `version` names the devstack in the marker line and the docs links: this
/// one, or an installed skill's own to tell whether more than that differs.
fn render(tpl: &str, stack: &Stack, stack_file: &Path, version: &str) -> String {
    let file = file_name(stack_file);
    let vars: Vec<(&str, String)> = vec![
        (
            "marker",
            format!(
                "generated by devstack {version} from {file} {MARKER_TAG}: edits here are overwritten; put project specifics into a skill of your own"
            ),
        ),
        ("stack_name", stack.stack.name.clone()),
        ("stack_file", file),
        (
            "requires",
            stack
                .stack
                .requires
                .clone()
                .map_or_else(|| "any version".into(), |r| format!("devstack {r}")),
        ),
        ("repo_url", REPO_URL.into()),
        ("docs_url", format!("{REPO_URL}/blob/v{version}/docs")),
        ("services_table", services_table(stack)),
        ("held_paths", held_paths(stack)),
        ("commands_table", commands_table(stack)),
        ("start_check", start_check(stack)),
    ];
    // The frontmatter is YAML: its values are double-quoted scalars, so what
    // goes into them is escaped for that (a file name with `"` or `: `).
    let (front, body) = split_frontmatter(tpl);
    let fill = |text: &str, escape: fn(&str) -> String| {
        let mut out = text.to_string();
        for (k, v) in &vars {
            out = out.replace(&format!("{{{{devstack:{k}}}}}"), &escape(v));
        }
        out
    };
    let mut out = fill(front, yaml_escape) + &fill(body, str::to_string);
    // An empty section leaves a gap of blank lines behind.
    while out.contains("\n\n\n") {
        out = out.replace("\n\n\n", "\n\n");
    }
    out
}

/// `---\n…\n---\n` and the rest; no frontmatter: an empty one.
fn split_frontmatter(tpl: &str) -> (&str, &str) {
    let Some(rest) = tpl.strip_prefix("---\n") else {
        return ("", tpl);
    };
    match rest.find("\n---\n") {
        Some(i) => tpl.split_at(4 + i + 5),
        None => ("", tpl),
    }
}

/// For the inside of a YAML double-quoted scalar.
fn yaml_escape(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "")
}

/// Text from the stack file inside a Markdown table cell: one line, no
/// column break.
fn cell(s: &str) -> String {
    s.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

/// Text from the stack file as inline code, also when it holds backticks
/// (a longer fence, CommonMark), in a table cell too.
fn code(s: &str) -> String {
    let s = cell(s);
    let mut fence = String::from("`");
    while s.contains(fence.as_str()) {
        fence.push('`');
    }
    if fence.len() == 1 {
        format!("`{s}`")
    } else {
        format!("{fence} {s} {fence}")
    }
}

fn url(s: &Service) -> Option<String> {
    s.port.map(|p| format!("{}://localhost:{p}", s.scheme()))
}

fn services_table(stack: &Stack) -> String {
    let mut t = String::from(
        "| Service | Kind | URL | Health | A saved change |\n| --- | --- | --- | --- | --- |\n",
    );
    for (name, s) in &stack.services {
        let mut kind = format!("{:?}", s.kind).to_lowercase();
        if !s.autostart {
            kind.push_str(", on demand");
        }
        if !s.platforms.is_empty() {
            let p: Vec<String> = s
                .platforms
                .iter()
                .map(|p| format!("{p:?}").to_lowercase())
                .collect();
            let _ = write!(kind, ", {} only", p.join("/"));
        }
        let change = match s.kind {
            Kind::Devserver if s.restart_on.is_empty() => "hot reload".to_string(),
            Kind::Devserver => "hot reload; restart for `restart_on` files".to_string(),
            Kind::Job => "runs to completion before its dependants start".to_string(),
            _ if !s.watch.is_empty() && s.build.is_some() && s.health.is_some() => {
                "candidate build, switches when healthy".to_string()
            }
            _ if !s.watch.is_empty() && s.build.is_some() => {
                "candidate build, switches once it runs (no health check)".to_string()
            }
            _ => "nothing (restart by hand)".to_string(),
        };
        let _ = writeln!(
            t,
            "| `{name}` | {kind} | {} | {} | {change} |",
            url(s).unwrap_or_else(|| "-".into()),
            s.health
                .as_ref()
                .map_or_else(|| "-".into(), |h| code(&h.http)),
        );
    }
    if stack.services.is_empty() {
        t = "This stack has no native services.\n".into();
    }
    let containers: Vec<String> = stack
        .compose
        .iter()
        .flat_map(|(g, c)| c.services.iter().map(move |s| format!("`{g}.{s}`")))
        .collect();
    if !containers.is_empty() {
        let _ = write!(t, "\nContainers (Compose): {}.", containers.join(", "));
    }
    t
}

fn held_paths(stack: &Stack) -> String {
    let held: Vec<String> = stack
        .services
        .iter()
        .filter_map(|(name, s)| {
            let p = s.promote.as_ref()?;
            if p.hold_if_changed.is_empty() && p.auto {
                return None;
            }
            Some(if p.auto {
                format!(
                    "`{name}` holds a candidate that changed {}",
                    p.hold_if_changed
                        .iter()
                        .map(|g| code(g))
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            } else {
                format!("`{name}` holds every candidate")
            })
        })
        .collect();
    if held.is_empty() {
        String::new()
    } else {
        format!(
            "**Held for `devstack promote`** (ask the user first; promoting may run a migration): {}.",
            held.join("; ")
        )
    }
}

fn commands_table(stack: &Stack) -> String {
    if stack.commands.is_empty() {
        return "This stack defines no commands.".into();
    }
    let mut t = String::from("| `devstack run …` | What | Asks first |\n| --- | --- | --- |\n");
    for (name, c) in &stack.commands {
        let _ = writeln!(
            t,
            "| `{name}` | {} | {} |",
            cell(&c.description),
            if c.confirm.is_some() { "yes" } else { "-" }
        );
    }
    t
}

fn start_check(stack: &Stack) -> String {
    let lines: Vec<String> = stack
        .services
        .iter()
        .filter(|(_, s)| s.autostart && s.platforms.is_empty())
        .filter_map(|(name, s)| {
            let h = s.health.as_ref()?;
            Some(format!(
                "curl -sk -o /dev/null -w '%{{http_code}}\\n' {}{}   # {name}: 200",
                url(s)?,
                h.http
            ))
        })
        .collect();
    if lines.is_empty() {
        "# no service with a health check: `devstack status` is the check".into()
    } else {
        lines.join("\n")
    }
}

/// What `install` did with each skill.
pub enum Outcome {
    Written(PathBuf),
    Unchanged(PathBuf),
    /// A file of the same name the project wrote itself; left alone.
    Kept(PathBuf),
}

/// Write the skills into `dir`, or else into the folders `[agents] skills`
/// names, and refresh a generated copy found in another agent's folder (it is
/// devstack's, and would stay behind otherwise).
pub fn install(
    stack: &Stack,
    stack_file: &Path,
    dir: Option<&Path>,
    force: bool,
) -> Result<Vec<Outcome>> {
    let rendered = render_all(stack, stack_file);
    // The folder, and whether it was asked for (else only devstack's copies).
    let targets: Vec<(PathBuf, bool)> = match dir {
        Some(d) => vec![(d.to_path_buf(), true)],
        None => {
            let named = skill_dirs(stack, stack_file)?;
            let mut t: Vec<(PathBuf, bool)> = named.iter().map(|d| (d.clone(), true)).collect();
            for d in search_dirs(stack, stack_file)? {
                if !named.contains(&d) && rendered.iter().any(|(n, _)| generated(&d.join(n))) {
                    t.push((d, false));
                }
            }
            t
        }
    };
    let mut done = Vec::new();
    for (dir, asked) in targets {
        for (name, content) in &rendered {
            if !asked && !generated(&dir.join(name)) {
                continue;
            }
            done.push(write_one(&dir.join(name).join("SKILL.md"), content, force)?);
        }
    }
    Ok(done)
}

/// A generated skill in `skill_dir` (its own folder, `…/skills/devstack`).
fn generated(skill_dir: &Path) -> bool {
    std::fs::read_to_string(skill_dir.join("SKILL.md")).is_ok_and(|e| e.contains(MARKER_TAG))
}

fn write_one(path: &Path, content: &str, force: bool) -> Result<Outcome> {
    let path = path.to_path_buf();
    match std::fs::read_to_string(&path).ok() {
        Some(e) if normalize(&e) == normalize(content) => return Ok(Outcome::Unchanged(path)),
        Some(e) if !e.contains(MARKER_TAG) && !force => return Ok(Outcome::Kept(path)),
        _ => {}
    }
    std::fs::create_dir_all(path.parent().expect("has a parent"))
        .with_context(|| format!("create {}", path.display()))?;
    std::fs::write(&path, content).with_context(|| format!("write {}", path.display()))?;
    Ok(Outcome::Written(path))
}

fn normalize(s: &str) -> String {
    s.replace("\r\n", "\n")
}

/// The generated skills installed in the repository (in the folders
/// `[agents] skills` names and in the other agents' ones), held against what
/// this devstack would write for this stack file.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Installed {
    /// Generated skills found, by folder: `.claude/skills/devstack` (one the
    /// project wrote itself is not one).
    pub found: Vec<String>,
    /// Of those, the ones that differ from what `install` would write now,
    /// apart from the devstack version: a release whose skills read the same
    /// leaves them be.
    pub outdated: Vec<String>,
    /// The oldest devstack their marker lines name: the version the
    /// repository was last set up with. `None` when no marker names one.
    pub from: Option<String>,
}

/// What [`Installed`] says for this stack file; nothing when it does not load.
pub fn installed(stack_file: &Path) -> Installed {
    let Ok(stack) = devstack_config::load(stack_file) else {
        return Installed::default();
    };
    let Ok(dirs) = search_dirs(&stack, stack_file) else {
        return Installed::default();
    };
    let mut out = Installed::default();
    for dir in &dirs {
        for (name, tpl) in TEMPLATES {
            let Ok(e) = std::fs::read_to_string(dir.join(name).join("SKILL.md")) else {
                continue;
            };
            if !e.contains(MARKER_TAG) {
                continue;
            }
            let at = shown(stack_file, dir, name);
            // Held against this devstack's text as the version that wrote it.
            let version = marker_version(&e);
            let content = render(
                tpl,
                &stack,
                stack_file,
                version.as_deref().unwrap_or(VERSION),
            );
            if normalize(&e) != normalize(&content) {
                out.outdated.push(at.clone());
            }
            out.found.push(at);
            if let Some(v) = version {
                let older = out.from.as_deref().is_none_or(|f| {
                    devstack_config::version_order(&v) < devstack_config::version_order(f)
                });
                if older {
                    out.from = Some(v);
                }
            }
        }
    }
    out
}

/// The version in a generated skill's marker line (`generated by devstack 0.17.0 from …`).
fn marker_version(skill: &str) -> Option<String> {
    let line = skill.lines().find(|l| l.contains(MARKER_TAG))?;
    let v = line
        .split("generated by devstack ")
        .nth(1)?
        .split_whitespace()
        .next()?;
    devstack_config::version_order(v).map(|_| v.to_string())
}

/// Installed generated skills that differ from what this devstack would
/// write for this stack file.
pub fn outdated(stack_file: &Path) -> Vec<String> {
    installed(stack_file).outdated
}

/// One line for `devstack status` and the MCP status, if anything is outdated.
pub fn outdated_note(stack_file: &Path) -> Option<String> {
    let names = outdated(stack_file);
    (!names.is_empty()).then(|| {
        format!(
            "note: the agent skill(s) {} no longer match this devstack or stack file; `devstack skills install` refreshes them",
            names.join(", ")
        )
    })
}

