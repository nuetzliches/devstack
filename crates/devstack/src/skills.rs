//! Agent skills for the repository that uses devstack (`devstack skills install`).
//!
//! The binary carries the templates (`skills/` in the devstack repository) and
//! fills in what the stack file says: its services, commands, held paths and
//! the URLs to check after a start. A generated skill says so in a marker line;
//! installing again overwrites it, and `devstack status` notes when the
//! installed copy no longer matches this devstack or this stack file. What is
//! specific to a project beyond that belongs in a skill of the project's own,
//! which devstack never touches.

use anyhow::{Context, Result};
use devstack_config::Stack;
use devstack_config::model::{Kind, Service};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const VERSION: &str = devstack_config::VERSION;
const REPO_URL: &str = "https://github.com/nuetzliches/devstack";
/// The words that tell a generated skill from one a project wrote itself.
const MARKER_TAG: &str = "(devstack skills install)";

const TEMPLATES: &[(&str, &str)] = &[
    (
        "devstack",
        include_str!("../../../skills/devstack/SKILL.md"),
    ),
    (
        "devstack-config",
        include_str!("../../../skills/devstack-config/SKILL.md"),
    ),
];

/// Where the skills go by default: Claude Code's project skills.
pub fn default_dir(stack_file: &Path) -> Result<PathBuf> {
    Ok(repo(stack_file)?.join(".claude").join("skills"))
}

fn repo(stack_file: &Path) -> Result<PathBuf> {
    let abs = std::path::absolute(stack_file)?;
    Ok(abs.parent().map(Path::to_path_buf).unwrap_or(abs))
}

fn file_name(stack_file: &Path) -> String {
    stack_file
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_else(|| "devstack.toml".into())
}

/// Every skill, rendered for this stack: `(name, content)`.
pub fn render_all(stack: &Stack, stack_file: &Path) -> Vec<(&'static str, String)> {
    TEMPLATES
        .iter()
        .map(|(name, tpl)| (*name, render(tpl, stack, stack_file)))
        .collect()
}

fn render(tpl: &str, stack: &Stack, stack_file: &Path) -> String {
    let file = file_name(stack_file);
    let vars: Vec<(&str, String)> = vec![
        (
            "marker",
            format!(
                "generated by devstack {VERSION} from {file} {MARKER_TAG}: edits here are overwritten; put project specifics into a skill of your own"
            ),
        ),
        ("stack_name", stack.stack.name.clone()),
        ("stack_file", file),
        (
            "requires",
            stack
                .stack
                .requires
                .clone()
                .map_or_else(|| "any version".into(), |r| format!("devstack {r}")),
        ),
        ("repo_url", REPO_URL.into()),
        ("docs_url", format!("{REPO_URL}/blob/v{VERSION}/docs")),
        ("services_table", services_table(stack)),
        ("held_paths", held_paths(stack)),
        ("commands_table", commands_table(stack)),
        ("start_check", start_check(stack)),
    ];
    // The frontmatter is YAML: its values are double-quoted scalars, so what
    // goes into them is escaped for that (a file name with `"` or `: `).
    let (front, body) = split_frontmatter(tpl);
    let fill = |text: &str, escape: fn(&str) -> String| {
        let mut out = text.to_string();
        for (k, v) in &vars {
            out = out.replace(&format!("{{{{devstack:{k}}}}}"), &escape(v));
        }
        out
    };
    let mut out = fill(front, yaml_escape) + &fill(body, str::to_string);
    // An empty section leaves a gap of blank lines behind.
    while out.contains("\n\n\n") {
        out = out.replace("\n\n\n", "\n\n");
    }
    out
}

/// `---\n…\n---\n` and the rest; no frontmatter: an empty one.
fn split_frontmatter(tpl: &str) -> (&str, &str) {
    let Some(rest) = tpl.strip_prefix("---\n") else {
        return ("", tpl);
    };
    match rest.find("\n---\n") {
        Some(i) => tpl.split_at(4 + i + 5),
        None => ("", tpl),
    }
}

/// For the inside of a YAML double-quoted scalar.
fn yaml_escape(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('"', "\\\"")
        .replace('\n', "\\n")
        .replace('\r', "")
}

/// Text from the stack file inside a Markdown table cell: one line, no
/// column break.
fn cell(s: &str) -> String {
    s.split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
        .replace('|', "\\|")
}

/// Text from the stack file as inline code, also when it holds backticks
/// (a longer fence, CommonMark), in a table cell too.
fn code(s: &str) -> String {
    let s = cell(s);
    let mut fence = String::from("`");
    while s.contains(fence.as_str()) {
        fence.push('`');
    }
    if fence.len() == 1 {
        format!("`{s}`")
    } else {
        format!("{fence} {s} {fence}")
    }
}

fn url(s: &Service) -> Option<String> {
    s.port.map(|p| format!("{}://localhost:{p}", s.scheme()))
}

fn services_table(stack: &Stack) -> String {
    let mut t = String::from(
        "| Service | Kind | URL | Health | A saved change |\n| --- | --- | --- | --- | --- |\n",
    );
    for (name, s) in &stack.services {
        let mut kind = format!("{:?}", s.kind).to_lowercase();
        if !s.autostart {
            kind.push_str(", on demand");
        }
        if !s.platforms.is_empty() {
            let p: Vec<String> = s
                .platforms
                .iter()
                .map(|p| format!("{p:?}").to_lowercase())
                .collect();
            let _ = write!(kind, ", {} only", p.join("/"));
        }
        let change = match s.kind {
            Kind::Devserver if s.restart_on.is_empty() => "hot reload".to_string(),
            Kind::Devserver => "hot reload; restart for `restart_on` files".to_string(),
            Kind::Job => "runs to completion before its dependants start".to_string(),
            _ if !s.watch.is_empty() && s.build.is_some() && s.health.is_some() => {
                "candidate build, switches when healthy".to_string()
            }
            _ if !s.watch.is_empty() && s.build.is_some() => {
                "candidate build, switches once it runs (no health check)".to_string()
            }
            _ => "nothing (restart by hand)".to_string(),
        };
        let _ = writeln!(
            t,
            "| `{name}` | {kind} | {} | {} | {change} |",
            url(s).unwrap_or_else(|| "-".into()),
            s.health
                .as_ref()
                .map_or_else(|| "-".into(), |h| code(&h.http)),
        );
    }
    if stack.services.is_empty() {
        t = "This stack has no native services.\n".into();
    }
    let containers: Vec<String> = stack
        .compose
        .iter()
        .flat_map(|(g, c)| c.services.iter().map(move |s| format!("`{g}.{s}`")))
        .collect();
    if !containers.is_empty() {
        let _ = write!(t, "\nContainers (Compose): {}.", containers.join(", "));
    }
    t
}

fn held_paths(stack: &Stack) -> String {
    let held: Vec<String> = stack
        .services
        .iter()
        .filter_map(|(name, s)| {
            let p = s.promote.as_ref()?;
            if p.hold_if_changed.is_empty() && p.auto {
                return None;
            }
            Some(if p.auto {
                format!(
                    "`{name}` holds a candidate that changed {}",
                    p.hold_if_changed
                        .iter()
                        .map(|g| code(g))
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            } else {
                format!("`{name}` holds every candidate")
            })
        })
        .collect();
    if held.is_empty() {
        String::new()
    } else {
        format!(
            "**Held for `devstack promote`** (ask the user first; promoting may run a migration): {}.",
            held.join("; ")
        )
    }
}

fn commands_table(stack: &Stack) -> String {
    if stack.commands.is_empty() {
        return "This stack defines no commands.".into();
    }
    let mut t = String::from("| `devstack run …` | What | Asks first |\n| --- | --- | --- |\n");
    for (name, c) in &stack.commands {
        let _ = writeln!(
            t,
            "| `{name}` | {} | {} |",
            cell(&c.description),
            if c.confirm.is_some() { "yes" } else { "-" }
        );
    }
    t
}

fn start_check(stack: &Stack) -> String {
    let lines: Vec<String> = stack
        .services
        .iter()
        .filter(|(_, s)| s.autostart && s.platforms.is_empty())
        .filter_map(|(name, s)| {
            let h = s.health.as_ref()?;
            Some(format!(
                "curl -sk -o /dev/null -w '%{{http_code}}\\n' {}{}   # {name}: 200",
                url(s)?,
                h.http
            ))
        })
        .collect();
    if lines.is_empty() {
        "# no service with a health check: `devstack status` is the check".into()
    } else {
        lines.join("\n")
    }
}

/// What `install` did with each skill.
pub enum Outcome {
    Written(PathBuf),
    Unchanged(PathBuf),
    /// A file of the same name the project wrote itself; left alone.
    Kept(PathBuf),
}

pub fn install(
    stack: &Stack,
    stack_file: &Path,
    dir: Option<&Path>,
    force: bool,
) -> Result<Vec<Outcome>> {
    let dir = match dir {
        Some(d) => d.to_path_buf(),
        None => default_dir(stack_file)?,
    };
    let mut done = Vec::new();
    for (name, content) in render_all(stack, stack_file) {
        let path = dir.join(name).join("SKILL.md");
        let existing = std::fs::read_to_string(&path).ok();
        match existing {
            Some(e) if normalize(&e) == normalize(&content) => {
                done.push(Outcome::Unchanged(path));
                continue;
            }
            Some(e) if !e.contains(MARKER_TAG) && !force => {
                done.push(Outcome::Kept(path));
                continue;
            }
            _ => {}
        }
        std::fs::create_dir_all(path.parent().expect("has a parent"))
            .with_context(|| format!("create {}", path.display()))?;
        std::fs::write(&path, &content).with_context(|| format!("write {}", path.display()))?;
        done.push(Outcome::Written(path));
    }
    Ok(done)
}

fn normalize(s: &str) -> String {
    s.replace("\r\n", "\n")
}

/// Installed generated skills (in the default directory) that differ from what
/// this devstack would write for this stack file.
pub fn outdated(stack_file: &Path) -> Vec<&'static str> {
    let (Ok(stack), Ok(dir)) = (devstack_config::load(stack_file), default_dir(stack_file)) else {
        return Vec::new();
    };
    render_all(&stack, stack_file)
        .into_iter()
        .filter(|(name, content)| {
            std::fs::read_to_string(dir.join(name).join("SKILL.md"))
                .is_ok_and(|e| e.contains(MARKER_TAG) && normalize(&e) != normalize(content))
        })
        .map(|(name, _)| name)
        .collect()
}

/// One line for `devstack status` and the MCP status, if anything is outdated.
pub fn outdated_note(stack_file: &Path) -> Option<String> {
    let names = outdated(stack_file);
    (!names.is_empty()).then(|| {
        format!(
            "note: the agent skill(s) {} no longer match this devstack or stack file; `devstack skills install` refreshes them",
            names.join(", ")
        )
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn stack() -> Stack {
        let toml = r#"
version = 1
[stack]
name = "shop"
requires = "0.2.0"
[compose.app]
project = "shop-dev"
files = ["compose.yml"]
services = ["db"]
[services.api]
build = "dotnet build"
output = "bin"
run = "dotnet {artifact}/Api.dll"
port = 5080
watch = ["src/**"]
health = { http = "/health/ready", timeout = "60s" }
promote = { hold_if_changed = ["src/Migrations/**"] }
[services.web]
kind = "devserver"
run = "npm start"
port = 4200
health = { http = "/", timeout = "120s", insecure_tls = true }
[commands.reset]
description = "Drop | recreate"
confirm = "Sure?"
steps = [{ exec = "true" }]
"#;
        devstack_config::from_str(toml, Path::new("devstack.toml")).unwrap()
    }

    #[test]
    fn every_placeholder_is_filled() {
        for (name, content) in render_all(&stack(), Path::new("devstack.toml")) {
            assert!(!content.contains("{{devstack:"), "{name}: {content}");
            assert!(content.contains(MARKER_TAG), "{name}");
            assert!(
                content.starts_with("---\nname: "),
                "{name}: frontmatter first"
            );
        }
    }

    /// The value of a YAML double-quoted scalar, or why it is not one.
    fn yaml_quoted(v: &str) -> Result<String, String> {
        let inner = v
            .strip_prefix('"')
            .ok_or_else(|| format!("not quoted: {v}"))?;
        let mut out = String::new();
        let mut chars = inner.chars();
        while let Some(c) = chars.next() {
            match c {
                '\\' => match chars.next() {
                    Some('n') => out.push('\n'),
                    Some(e @ ('\\' | '"')) => out.push(e),
                    other => return Err(format!("bad escape {other:?}")),
                },
                '"' => {
                    return if chars.as_str().is_empty() {
                        Ok(out)
                    } else {
                        Err(format!("text after the closing quote: {v}"))
                    };
                }
                c => out.push(c),
            }
        }
        Err(format!("no closing quote: {v}"))
    }

    /// Strict YAML parsers refuse `: ` in a plain scalar; every frontmatter
    /// value is a double-quoted one, also with an odd stack file name.
    #[test]
    fn the_frontmatter_is_strict_yaml() {
        let odd = Path::new("we\"ird: x.toml");
        for (name, content) in render_all(&stack(), odd) {
            let (front, _) = split_frontmatter(&content);
            assert!(!front.is_empty(), "{name}");
            for line in front.lines().filter(|l| *l != "---") {
                let (key, value) = line.split_once(": ").expect("key: value");
                assert!(["name", "description"].contains(&key), "{name}: {line}");
                if key == "description" {
                    let text = yaml_quoted(value).unwrap_or_else(|e| panic!("{name}: {e}"));
                    assert!(text.contains("we\"ird: x.toml"), "{name}: {text}");
                } else {
                    assert!(!value.contains(": "), "{name}: {line}");
                }
            }
        }
    }

    #[test]
    fn stack_file_text_stays_inside_its_cell() {
        assert_eq!(cell("a | b\nc"), "a \\| b c");
        assert_eq!(code("/health"), "`/health`");
        assert_eq!(code("a`b"), "`` a`b ``");
    }

    #[test]
    fn the_stack_shows_up() {
        let all = render_all(&stack(), Path::new("devstack.toml"));
        let ops = &all.iter().find(|(n, _)| *n == "devstack").unwrap().1;
        assert!(
            ops.contains("| `api` | service | http://localhost:5080 | `/health/ready` |"),
            "{ops}"
        );
        assert!(ops.contains("https://localhost:4200"), "TLS dev server");
        assert!(ops.contains("`app.db`"));
        assert!(ops.contains("`src/Migrations/**`"));
        assert!(
            ops.contains("| `reset` | Drop \\| recreate | yes |"),
            "pipe escaped"
        );
        assert!(ops.contains(
            "curl -sk -o /dev/null -w '%{http_code}\\n' http://localhost:5080/health/ready"
        ));
        assert!(ops.contains("needs devstack 0.2.0 or newer"));
    }

    #[test]
    fn install_keeps_a_skill_the_project_wrote() {
        let dir = tempfile::tempdir().unwrap();
        let own = dir.path().join("devstack").join("SKILL.md");
        std::fs::create_dir_all(own.parent().unwrap()).unwrap();
        std::fs::write(&own, "---\nname: devstack\n---\nours").unwrap();
        let s = stack();
        let out = install(&s, Path::new("devstack.toml"), Some(dir.path()), false).unwrap();
        assert!(matches!(out[0], Outcome::Kept(_)));
        assert!(matches!(out[1], Outcome::Written(_)));
        assert_eq!(
            std::fs::read_to_string(&own).unwrap(),
            "---\nname: devstack\n---\nours"
        );
        let again = install(&s, Path::new("devstack.toml"), Some(dir.path()), true).unwrap();
        assert!(
            matches!(again[0], Outcome::Written(_)),
            "--force overwrites"
        );
        let third = install(&s, Path::new("devstack.toml"), Some(dir.path()), false).unwrap();
        assert!(third.iter().all(|o| matches!(o, Outcome::Unchanged(_))));
    }
}
